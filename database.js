const fs = require('node:fs');
const path = require('node:path');
const { AsyncLocalStorage } = require('node:async_hooks');
const { Pool, types } = require('pg');

types.setTypeParser(20, (value) => Number(value));
types.setTypeParser(1082, (value) => value);
types.setTypeParser(1700, (value) => (value === null ? null : Number(value)));

const requiredEnv = ['PGHOST', 'PGUSER', 'PGPASSWORD', 'PGDATABASE'];
const missingEnv = requiredEnv.filter((key) => !process.env[key]);
if (missingEnv.length) {
  throw new Error(`Configure ${missingEnv.join(', ')} no arquivo .env antes de iniciar.`);
}

const pool = new Pool({
  host: process.env.PGHOST,
  port: Number(process.env.PGPORT || 5432),
  database: process.env.PGDATABASE,
  user: process.env.PGUSER,
  password: process.env.PGPASSWORD,
  ssl: { rejectUnauthorized: false },
  max: process.env.VERCEL ? 1 : 5,
  idleTimeoutMillis: 10000,
  connectionTimeoutMillis: 15000,
  application_name: 'vertice-agro'
});

pool.on('error', (error) => {
  console.error('Falha na conexão ociosa com o Supabase:', error.message);
});

const connection = new AsyncLocalStorage();
const schemaSql = fs.readFileSync(path.join(__dirname, 'supabase', 'schema.sql'), 'utf8');
const identifiers = [...new Set([...schemaSql.matchAll(/"([A-Za-z_][A-Za-z0-9_]*)"/g)].map((match) => match[1]))]
  .sort((left, right) => right.length - left.length);
const primaryKeys = {};

for (const block of schemaSql.split('CREATE TABLE IF NOT EXISTS ').slice(1)) {
  const table = block.match(/^"([^"]+)"/);
  const primaryKey = block.match(/"([^"]+)"\s+INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  if (table && primaryKey) primaryKeys[table[1]] = primaryKey[1];
}

function translateError(error) {
  if (error?.code === '23505') error.code = 'SQLITE_CONSTRAINT_UNIQUE';
  else if (error?.code === '23503') error.code = 'SQLITE_CONSTRAINT_FOREIGNKEY';
  else if (error?.code === '23514') error.code = 'SQLITE_CONSTRAINT_TRIGGER';
  return error;
}

function rewriteOutsideStrings(sql, rewriteCode) {
  let output = '';
  for (let index = 0; index < sql.length;) {
    if (sql[index] === "'") {
      const start = index;
      index += 1;
      while (index < sql.length) {
        if (sql[index] === "'" && sql[index + 1] === "'") {
          index += 2;
          continue;
        }
        if (sql[index] === "'") {
          index += 1;
          break;
        }
        index += 1;
      }
      output += sql.slice(start, index);
      continue;
    }
    const next = rewriteCode(sql, index);
    if (next) {
      output += next.text;
      index = next.index;
      continue;
    }
    output += sql[index];
    index += 1;
  }
  return output;
}

function translate(sql) {
  let translated = sql.replace(/([A-Za-z_][\w.]*)\s*=\s*\?\s+COLLATE\s+NOCASE/gi, 'lower($1) = lower(?)');
  translated = translated.replace(/\s+COLLATE\s+NOCASE/gi, '');
  translated = translated.replace(/\bdate\s*\(\s*([A-Za-z_][\w.]*)\s*\)/gi, '$1');
  translated = translated.replace(/\bLIKE\b/g, 'ILIKE');
  translated = rewriteOutsideStrings(translated, (current, index) => {
    if (current[index] === '"') {
      const end = current.indexOf('"', index + 1);
      return { text: current.slice(index, end + 1), index: end + 1 };
    }
    if (!/[A-Za-z_]/.test(current[index]) || (index > 0 && /[A-Za-z0-9_]/.test(current[index - 1]))) return null;
    const name = identifiers.find((identifier) => current.startsWith(identifier, index)
      && !/[A-Za-z0-9_]/.test(current[index + identifier.length] || ''));
    return name ? { text: `"${name}"`, index: index + name.length } : null;
  });
  let parameter = 0;
  translated = rewriteOutsideStrings(translated, (current, index) => (
    current[index] === '?' ? { text: `$${++parameter}`, index: index + 1 } : null
  ));
  if (/^\s*insert\s+into\s+/i.test(translated) && !/\breturning\b/i.test(translated)) {
    const table = translated.match(/^\s*insert\s+into\s+"([^"]+)"/i);
    const primaryKey = table && primaryKeys[table[1]];
    if (primaryKey) translated = `${translated.replace(/;\s*$/, '')} RETURNING "${primaryKey}"`;
  }
  return translated;
}

async function execute(sql, params) {
  const executor = connection.getStore() || pool;
  try {
    return await executor.query(translate(sql), params);
  } catch (error) {
    throw translateError(error);
  }
}

function prepare(sql) {
  return {
    get: async (...params) => (await execute(sql, params)).rows[0],
    all: async (...params) => (await execute(sql, params)).rows,
    run: async (...params) => {
      const result = await execute(sql, params);
      const primaryKey = Object.keys(result.rows[0] || {}).find((column) => result.rows[0][column] !== undefined);
      return {
        changes: result.rowCount,
        lastInsertRowid: result.rows[0] ? result.rows[0][primaryKey] : undefined
      };
    }
  };
}

function transaction(work) {
  const run = async () => {
    if (connection.getStore()) return work();
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query('SELECT pg_advisory_xact_lock(418210)');
      const result = await connection.run(client, work);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      try { await client.query('ROLLBACK'); } catch { /* a transação já foi encerrada */ }
      throw error;
    } finally {
      client.release();
    }
  };
  run.immediate = run;
  return run;
}

async function prepareDatabase() {
  await pool.query('SELECT 1');
  await pool.query(`
    CREATE TABLE IF NOT EXISTS app_session (
      sid varchar NOT NULL COLLATE "default",
      sess json NOT NULL,
      expire timestamp(6) NOT NULL,
      CONSTRAINT app_session_pkey PRIMARY KEY (sid)
    )
  `);
  await pool.query('CREATE INDEX IF NOT EXISTS "IDX_app_session_expire" ON app_session (expire)');
  await pool.query('ALTER TABLE app_session ENABLE ROW LEVEL SECURITY');
}

const ready = prepareDatabase();

module.exports = { prepare, transaction, ready, pool };
